function tsEscape(value) {
  return value.replace(/\\/g, '\\\\').replace(/'/g, "\\'")
}

let failed = false

for (const locale of LOCALES) {
  const path = `src/i18n/messages/${locale}.ts`
  const dict = T[locale]
  if (!dict) {
    console.error(`${locale}: no translations table — aborting this file`)
    failed = true
    continue
  }
  const missing = KEYS.filter((k) => !(k in dict))
  if (missing.length > 0) {
    console.error(`${locale}: missing translations: ${missing.join(', ')} — aborting this file`)
    failed = true
    continue
  }

  const src = readFileSync(path, 'utf8')

  // Anchor: the closing "}," of the ads object right before `  adSlot: {`.
  const adIdx = src.indexOf('\n  adSlot: {')
  if (adIdx === -1) {
    console.error(`${locale}: adSlot anchor not found — aborting this file`)
    failed = true
    continue
  }
  const closeIdx = src.lastIndexOf('\n  },', adIdx)
  if (closeIdx === -1) {
    console.error(`${locale}: ads closing brace not found — aborting this file`)
    failed = true
    continue
  }

  // Safety: never insert a key twice.
  const block = src.slice(closeIdx - 4000, closeIdx)
  const dup = KEYS.filter((k) => new RegExp(`\\b${k}: `).test(block))
  if (dup.length > 0) {
    console.error(`${locale}: keys already present: ${dup.join(', ')} — aborting this file`)
    failed = true
    continue
  }

  const lines = [
    '    // ---- Phase 4: A/B testing + delivery forecast ----',
    ...KEYS.map((k) => `    ${k}: '${tsEscape(dict[k])}',`),
  ].join('\n')
  const out = src.slice(0, closeIdx) + '\n' + lines + src.slice(closeIdx)
  writeFileSync(path, out)
  console.log(`${locale}: ok (${KEYS.length} keys)`)
}

if (failed) {
  console.error('FAILED — check the errors above')
  process.exit(1)
}
console.log('done')
