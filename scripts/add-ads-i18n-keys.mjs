function tsEscape(s) {
  return s.replace(/\\/g, '\\\\').replace(/'/g, "\\'")
}

let failed = false
for (const [locale, dict] of Object.entries(T)) {
  const path = `src/i18n/messages/${locale}.ts`
  let src = readFileSync(path, 'utf8')

  // 1) Replace the two changed values in place.
  for (const key of UPDATED) {
    const re = new RegExp(`(\\b${key}: )'[^']*'`)
    if (!re.test(src)) {
      console.error(`${locale}: ${key} not found — aborting this file`)
      failed = true
      continue
    }
    src = src.replace(re, `$1'${tsEscape(dict[key])}'`)
  }

  // 2) Insert the new keys just before the closing "}," of the ads object
  //    (the object that directly precedes `  adSlot: {`).
  const adIdx = src.indexOf('\n  adSlot: {')
  if (adIdx === -1) {
    console.error(`${locale}: adSlot anchor not found — aborting this file`)
    failed = true
    continue
  }
  const closeIdx = src.lastIndexOf('\n  },', adIdx)
  if (closeIdx === -1) {
    console.error(`${locale}: ads closing brace not found — aborting this file`)
    failed = true
    continue
  }
  const lines = Object.entries(dict)
    .filter(([k]) => !UPDATED.includes(k))
    .map(([k, v]) => `    ${k}: '${tsEscape(v)}',`)
    .join('\n')
  src = src.slice(0, closeIdx) + '\n' + lines + src.slice(closeIdx)

  writeFileSync(path, src)
  console.log(`${locale}: ok`)
}

if (failed) {
  console.error('FAILED — check the errors above')
  process.exit(1)
}
